/**
 * Assemble a complete LessonPlan from AI-generated chunk content.
 *
 * This function is DETERMINISTIC — same input always produces same output.
 * It NEVER calls the AI or makes any network requests.
 *
 * TEACH-FIRST SEQUENCE (Bug fixes 2.3.4 + 2.3.8):
 * Each chunk goes through exactly 5 steps in a fixed order. The old
 * activitySequencer approach randomly selected types from a pool, which
 * caused repeated types within a single chunk's quiz steps. The fixed
 * sequence guarantees INFO → MC(meaning) → FILL_BLANK → TRANSLATE →
 * MC(usage context) — five distinct types per chunk, escalating difficulty.
 *
 * introChunks is populated so LessonView can show a LessonIntroCard
 * before step 0, giving learners a mental map of what they'll learn.
 *
 * @param content - AI-generated chunk content (from generateChunksForTopic)
 * @param lessonId - Unique lesson ID supplied by the caller
 * @param options - Optional settings (difficulty unused now, kept for API compat)
 * @returns A fully populated LessonPlan ready for LessonView
 */
export function assembleLessonPlan(
  content: AILessonContent,
  lessonId: string,
  options?: { difficulty?: number; seed?: number }
): LessonPlan {
  const targetLangName = toLanguageName(content.targetLanguageCode);

  // Build all steps using the fixed 5-step teach-first sequence per chunk.
  // This call order is guaranteed: INFO → MC → FILL_BLANK → TRANSLATE → MC(usage)
  const steps: LessonStep[] = [];
  for (const chunk of content.chunks) {
    steps.push(...assembleTeachFirstSteps(chunk, targetLangName));
  }

  const totalSunDrops = steps.reduce((sum, step) => sum + step.activity.sunDrops, 0);

  // Count distinct activity types for logging (should always be 4 — INFO, MC, FB, TRANSLATE)
  const activityTypes = new Set(steps.map(s => s.activity.type));

  console.log(
    `[lessonAssembler] Assembled ${steps.length} steps for ${content.chunks.length} chunks ` +
    `(${totalSunDrops} SunDrops, ${activityTypes.size} distinct types: ${[...activityTypes].join(', ')})`
  );

  return {
    id: lessonId,
    title: content.title,
    icon: '📚',
    skillPathId: content.title,
    lessonIndex: 0,
    steps,
    totalSunDrops,
    // LessonIntroCard preview data (Task 2.3.4)
    // One entry per chunk — shown before step 0 so learners know what's coming.
    introChunks: content.chunks.map(c => ({
      targetPhrase: c.targetPhrase,
      nativeTranslation: c.nativeTranslation,
    })),
    // Phase 3 metadata (Task 3.2, 3.6) — passed through to LessonIntroCard
    coreFrame: content.coreFrame,
    coreFrameTranslation: content.coreFrameTranslation,
    personalContext: content.personalContext,
  };
}

/**
 * Get the correct option index for a shuffled multiple-choice question.
 *
 * Deterministic: same answer string → same position every time.
 * The correct answer won't always be at index 0 (which is obviously wrong)
 * but the position is stable across renders.
 *
 * @param correctAnswer - The correct option text
 * @returns Index 0-3
 */
export function getCorrectIndex(correctAnswer: string): number {
  // Use string length mod 4 — simple, deterministic, distributes across 0-3
  return correctAnswer.length % 4;
}

// ============================================================================
// CORE ASSEMBLY — TEACH-FIRST 5-STEP PROGRESSION
// ============================================================================

/**
 * Build the 5 teach-first steps for a single chunk.
 *
 * ORDER IS MANDATORY:
 *   1. COACHING   (COACHING_CHAT/INFO) — NPC-guided discovery, or INFO fallback
 *   2. RECOGNIZE  (MULTIPLE_CHOICE) — guided MC with hint available
 *   3. PRACTICE   (FILL_BLANK)      — complete part of the phrase
 *   4. RECALL     (TRANSLATE)       — full translation from native to target
 *   5. APPLY      (MULTIPLE_CHOICE) — contextual usage question
 */
function assembleTeachFirstSteps(
  chunk: GeneratedChunkContent,
  targetLangName: string
): LessonStep[] {
  return [
    buildCoachingStep(chunk),
    buildRecognizeStep(chunk),
    buildPracticeStep(chunk),
    buildRecallStep(chunk, targetLangName),
    buildApplyStep(chunk),
  ];
}

// ── STEP 1: COACHING / INTRODUCE ─────────────────────────────────────────────

/**
 * Build the first step for a chunk: COACHING_CHAT if the AI provided coaching
 * fields (Phase 3), or a plain INFO card as a graceful fallback (Phase 3 Rule 14).
 *
 * The coaching step is an NPC-guided discovery exchange — the learner taps one
 * of 3 options to "discover" the meaning of the new phrase. There is NO failure
 * state: wrong answers get warm encouragement, the correct answer is always
 * revealed, and 0 SunDrops are awarded (Rule 10).
 *
 * Falls back to INFO when:
 *  - discoveryQuestion is absent (fallback / old generation)
 *  - discoveryOptions is absent or empty
 *  - Any other coaching field is missing
 */
function buildCoachingStep(chunk: GeneratedChunkContent): LessonStep {
  // Require at minimum: discoveryQuestion + 2 discoveryOptions + discoveryFollowUp
  const hasCoachingFields =
    chunk.discoveryQuestion &&
    chunk.discoveryOptions &&
    chunk.discoveryOptions.length >= 2 &&
    typeof chunk.discoveryCorrectIndex === 'number' &&
    chunk.discoveryFollowUp;

  if (hasCoachingFields) {
    return {
      tutorText: `🌟 Let's discover something new!`,
      helpText: chunk.explanation,
      // coachingText on LessonStep drives the TTS pre-play (useLessonAudio).
      // Embedding the same text on the activity so CoachingChat.tsx can also
      // read it without going up to the parent step via prop drilling.
      coachingText: chunk.coachingText,
      activity: {
        type: GameActivityType.COACHING_CHAT,
        // Coaching introduction (spoken by NPC via TTS)
        coachingText: chunk.coachingText,
        // Phrase being discovered
        targetPhrase: chunk.targetPhrase,
        nativeTranslation: chunk.nativeTranslation,
        // Discovery question + options (tap-to-choose for 7-14, free-text later)
        discoveryQuestion: chunk.discoveryQuestion!,
        discoveryOptions: chunk.discoveryOptions!,
        discoveryCorrectIndex: chunk.discoveryCorrectIndex!,
        // Warm follow-up regardless of right/wrong answer
        discoveryFollowUp: chunk.discoveryFollowUp!,
        // Pattern reinforcement (optional — only shown if AI supplied it)
        patternHighlight: chunk.patternHighlight,
        // 0 SunDrops — coaching is discovery, not assessment (Rule 10)
        sunDrops: 0,
      },
    };
  }

  // Fallback: plain INFO card (no coaching fields available)
  return buildIntroduceStep(chunk);
}

/**
 * Show the phrase + translation. No quiz. No pressure.
 * The learner MUST see this before any quiz step.
 *
 * Used as a fallback when coaching fields are absent (Phase 3 Rule 14).
 * Also used directly for review/SRS mode in Phase 4.
 *
 * coachingText is included for TTS playback (Task 2.0.07).
 */
function buildIntroduceStep(chunk: GeneratedChunkContent): LessonStep {
  return {
    tutorText: `📚 New phrase: "${chunk.targetPhrase}"`,
    helpText: chunk.explanation,
    coachingText: chunk.coachingText, // AI-generated intro for TTS
    activity: {
      type: GameActivityType.INFO,
      title: chunk.targetPhrase,
      content: `${chunk.targetPhrase} = "${chunk.nativeTranslation}"`,
      explanation: chunk.explanation,
      example: chunk.exampleSentence,
      sunDrops: 0,
    },
  };
}

// ── STEP 2: RECOGNIZE ────────────────────────────────────────────────────────

/**
 * Multiple choice: "What does [target phrase] mean?"
 * Options are all in the NATIVE language (correct answer + 3 distractors).
 * Hint reminds the learner of the answer — this is GUIDED practice.
 */
function buildRecognizeStep(chunk: GeneratedChunkContent): LessonStep {
  const options = shuffleWithCorrectAt(chunk.nativeTranslation, chunk.distractors);
  const correctIndex = getCorrectIndex(chunk.nativeTranslation);

  return {
    tutorText: `Let's check — what does "${chunk.targetPhrase}" mean?`,
    helpText: `Remember: "${chunk.targetPhrase}" = "${chunk.nativeTranslation}"`,
    activity: {
      type: GameActivityType.MULTIPLE_CHOICE,
      question: `What does "${chunk.targetPhrase}" mean?`,
      options,
      correctIndex,
      hint: `"${chunk.targetPhrase}" = "${chunk.nativeTranslation}"`,
      sunDrops: 1,
    },
  };
}

// ── STEP 3: PRACTICE ─────────────────────────────────────────────────────────

/**
 * Fill in the blank — recall part of the phrase.
 *
 * Multi-word phrase → blank the last word: "Guten ___"
 * Single-word phrase → "___ = 'translation'" format
 *
 * Hint is available but not shown by default.
 */
function buildPracticeStep(chunk: GeneratedChunkContent): LessonStep {
  const sentence = buildFillBlankSentence(chunk);
  const correctAnswer = getFillBlankAnswer(chunk);
  const acceptedAnswers = getFillBlankAcceptedAnswers(chunk);

  return {
    tutorText: `Practice time! Complete this phrase.`,
    helpText: `The full phrase is: "${chunk.targetPhrase}"`,
    activity: {
      type: GameActivityType.FILL_BLANK,
      sentence,
      correctAnswer,
      acceptedAnswers,
      hint: `"${chunk.targetPhrase}" = "${chunk.nativeTranslation}"`,
      sunDrops: 2,
    },
  };
}

// ── STEP 4: RECALL ────────────────────────────────────────────────────────────

/**
 * Translate from native language to target language.
 * No hints shown by default — this is where retention is tested.
 * Multiple accepted answer variants handle capitalisation and punctuation.
 */
function buildRecallStep(chunk: GeneratedChunkContent, targetLangName: string): LessonStep {
  const acceptedAnswers = getTranslateAcceptedAnswers(chunk);

  return {
    tutorText: `Your turn! How do you say "${chunk.nativeTranslation}" in ${targetLangName}?`,
    helpText: `Think about the phrase we just practised...`,
    activity: {
      type: GameActivityType.TRANSLATE,
      sourcePhrase: chunk.nativeTranslation,
      // correctAnswer is the canonical form — Translate.tsx requires this for its
      // validation check and "show answer after X wrong attempts" feature.
      // acceptedAnswers includes lowercase/punctuation variants so kids aren't penalised.
      correctAnswer: chunk.targetPhrase,
      acceptedAnswers,
      hint: `It starts with "${chunk.targetPhrase.substring(0, 3)}..."`,
      sunDrops: 3,
    },
  };
}

// ── STEP 5: APPLY ─────────────────────────────────────────────────────────────

/**
 * Contextual multiple choice: "When would you say [phrase]?"
 * Options are all in the NATIVE language (correct situation + 3 wrong situations).
 */
function buildApplyStep(chunk: GeneratedChunkContent): LessonStep {
  const options = shuffleWithCorrectAt(chunk.correctUsageContext, chunk.wrongUsageContexts);
  const correctIndex = getCorrectIndex(chunk.correctUsageContext);

  return {
    tutorText: `Great! Now, when would you say "${chunk.targetPhrase}"?`,
    helpText: chunk.usageNote,
    activity: {
      type: GameActivityType.MULTIPLE_CHOICE,
      question: `When would you say "${chunk.targetPhrase}"?`,
      options,
      correctIndex,
      hint: chunk.usageNote,
      sunDrops: 2,
    },
  };
}

