/**
 * LingoFriends — Lesson Assembler
 *
 * DETERMINISTIC lesson assembly from AI-generated chunk content.
 *
 * ARCHITECTURE RULE (see .clinerules):
 *   The AI generates CONTENT (phrases, translations, distractors, contexts).
 *   This module builds ACTIVITIES (ActivityConfig objects).
 *   These two concerns are NEVER mixed.
 *
 * TEACH-FIRST 5-STEP PROGRESSION (Bug fix 2.3.4 + 2.3.8):
 *   Every chunk is taught through exactly these 5 steps in order:
 *   1. INTRODUCE  — INFO card showing phrase + translation (0 SunDrops)
 *   2. RECOGNIZE  — MC "What does [phrase] mean?" in native language (1 SunDrop)
 *   3. PRACTICE   — Fill-blank to complete the phrase (2 SunDrops)
 *   4. RECALL     — Translate native → target language (3 SunDrops)
 *   5. APPLY      — MC "When would you say [phrase]?" situational (2 SunDrops)
 *
 * This replaces the Phase 1.3 activitySequencer approach which picked quiz types
 * randomly from a pool. The sequencer caused Bug 2.3.8 — the same type could
 * appear twice on the same chunk (e.g., MC → MC or TRUE_FALSE → MC), making
 * lessons feel repetitive. The fixed 5-step sequence guarantees:
 *   - Every chunk gets FIVE DISTINCT activity types
 *   - INTRODUCE always precedes any quiz (Bug 2.3.4 compliance)
 *   - RECOGNIZE and APPLY are both MC but ask different questions
 *   - Activity difficulty escalates within each chunk
 *
 * The activitySequencer.ts is preserved for potential use in review/SRS mode
 * (Phase 3), but is NOT imported or used here.
 *
 * This module has ZERO dependency on the AI client. It is pure TypeScript
 * and always produces valid, fully-populated ActivityConfig objects.
 *
 * @module lessonAssembler
 */

import { GameActivityType } from '../types/game';
import type { ActivityConfig, LessonStep, LessonPlan } from '../types/game';
import { toLanguageName } from '../utils/languageUtils';

// activitySequencer is intentionally NOT imported here.
// The sequencer was used in Phase 1.3 for random variety but produced
// repetitive activity types across chunks (Bug 2.3.8). The fixed
// 5-step teach-first sequence (assembleTeachFirstSteps) is pedagogically
// superior and guarantees distinct activity types per chunk.
// The sequencer is still available for future review/SRS mode — see Phase 3 plans.

// ============================================================================
// TYPES — THE ONLY INTERFACE BETWEEN AI OUTPUT AND LESSON ASSEMBLY
// ============================================================================

/**
 * A single lexical chunk generated by the AI.
 *
 * CRITICAL CONTRACT:
 * - All distractors MUST be in the NATIVE language (same as nativeTranslation).
 *   Example for "Guten Morgen" (native = English):
 *     distractors: ["Good evening", "Good night", "Goodbye"]  ✅
 *     distractors: ["Guten Abend", "Gute Nacht", "Tschüss"]   ❌ (target language!)
 *
 * - All usage contexts MUST be in the NATIVE language.
 *
 * If the AI doesn't follow these rules, the validator will catch it.
 */
export interface GeneratedChunkContent {
  /** Phrase in the target language: "Guten Morgen" */
  targetPhrase: string;

  /** Translation in the native language: "Good morning" */
  nativeTranslation: string;

  /** Example sentence using the phrase in the target language: "Guten Morgen! Wie geht's?" */
  exampleSentence: string;

  /** When/how to use this phrase, in the native language: "Use as a morning greeting" */
  usageNote: string;

  /** Child-friendly explanation in the native language: "A polite way to say hello in the morning" */
  explanation: string;

  /**
   * 3 wrong translations in the NATIVE language.
   * Must be plausible (same semantic category) but clearly wrong.
   * NEVER in the target language.
   */
  distractors: [string, string, string];

  /** The correct situation for using this phrase, in the native language */
  correctUsageContext: string;

  /**
   * 3 wrong usage situations in the NATIVE language.
   * Must be plausible but incorrect.
   */
  wrongUsageContexts: [string, string, string];

  /**
   * AI-generated coaching introduction for this chunk (Task 2.0.07 / Phase 3).
   * Spoken by the NPC via TTS when the step begins.
   * Written in the user's native language with target language examples.
   * Provides context, motivation, and personalisation.
   * Example: "Let's learn how to greet someone in the morning! In German, you'd say 'Guten Morgen'."
   */
  coachingText?: string;

  // ── Phase 3 coaching discovery fields (Task 3.4) ──────────────────────────
  /**
   * Discovery question the NPC asks, e.g. "Which word do you think means 'cat'?"
   * Non-threatening — wrong answers always get encouragement, never failure.
   */
  discoveryQuestion?: string;

  /**
   * Tap-to-choose options for the discovery question.
   * Typically 3 items: the correct answer + 2 distractors.
   * Generated by the AI using the chunk's distractors.
   */
  discoveryOptions?: string[];

  /**
   * Index of the correct option in discoveryOptions (0-based).
   * The correct answer is always revealed after the learner answers,
   * regardless of whether they got it right.
   */
  discoveryCorrectIndex?: number;

  /**
   * Encouraging follow-up text displayed after the learner taps an option.
   * Always warm — acknowledges the answer and reveals/confirms the correct one.
   * Example: "That's right! 'Katze' means cat. And 'Ich habe' means 'I have' — use it a lot!"
   */
  discoveryFollowUp?: string;

  /**
   * Pattern highlight shown after discovery to reinforce the chunk family concept.
   * Example: "Notice how 'Ich habe' stays the same — only the last part changes!"
   */
  patternHighlight?: string;
}

/**
 * Complete AI output for a lesson — CONTENT ONLY, no activity structure.
 * This is assembled into a LessonPlan by assembleLessonPlan().
 */
export interface AILessonContent {
  /** Lesson display title, e.g. "Morning Greetings" */
  title: string;

  /** Target language ISO code, e.g. "de" */
  targetLanguageCode: string;

  /** Native language ISO code, e.g. "en" */
  nativeLanguageCode: string;

  /** The chunks to teach in this lesson (2–4 recommended) */
  chunks: GeneratedChunkContent[];

  /** Learner interests used for personalising tutor text */
  interests?: string[];

  // ── Phase 3 metadata (Task 3.2) ───────────────────────────────────────────
  /**
   * The core sentence frame in the target language, e.g. "Ich habe ___".
   * Generated by the chunk family prompt — all chunks share this frame.
   * Absent for fallback lessons.
   */
  coreFrame?: string;

  /**
   * Translation of the core frame into the native language, e.g. "I have ___".
   */
  coreFrameTranslation?: string;

  /**
   * Personal context gathered from the pre-lesson chat (Task 3.3).
   * Passed through to the LessonPlan for display in the intro card.
   */
  personalContext?: string;
}

